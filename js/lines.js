// 받침에 맞는 조사: josa('팬더 브로치', '은', '는') → '는'. 한글이 아니면 받침 없는 쪽 (Clou → 는)
const josa = (w, withB, without) => {
  const c = w.charCodeAt(w.length - 1) - 0xac00;
  return c >= 0 && c < 11172 && c % 28 ? withB : without;
};

